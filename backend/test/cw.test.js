import { buildBookingXml } from "../src/lib/cwPayload.js";
import { sendBookingToCw } from "../src/lib/cwClient.js";
import { cwPublicConfig } from "../src/lib/config.js";
let pass = 0, fail = 0;
const ok = (name, cond) => { if (cond) { pass++; console.log("  \u2713", name); } else { fail++; console.log("  \u2717", name); } };
const booking = { mode: "Air", incotermCode: "EXW", freightTerms: "STD", originCode: "USMIA", destCode: "BSNAS", goodsDescription: "TELECOM EQUIPMENT", shipper: { companyName: "INTCOMEX", address1: "10310 NW 121ST WAY", postCode: "33178", city: "MEDLEY", state: "FL", country: "US" }, consignee: { companyName: "BAHAMAS TELECOMMUNICATIONS COMPANY", address1: "JOHN KENNEDY DR", postCode: "00000", city: "NASSAU", state: "BAHAMAS", country: "BS" }, cargoLines: [{ packages: 1, packageTypeCode: "CRT", grossWeight: 231, weightUnit: "KGS", volume: 1, volumeUnit: "M3" }, { packages: 1, packageTypeCode: "CRT", grossWeight: 53, weightUnit: "KGS", volume: 1, volumeUnit: "M3" }] };
const xml = buildBookingXml(booking);
ok("ServerID is TRN", xml.includes("<ServerID>TRN</ServerID>"));
ok("ServerID is NOT PRD", !xml.includes("<ServerID>PRD</ServerID>"));
ok("Mode mapped (Air → AIR)", /<TransportMode>\s*<Code>AIR<\/Code>/.test(xml));
ok("Origin/Destination mapped", /<Code>USMIA<\/Code>/.test(xml) && /<Code>BSNAS<\/Code>/.test(xml));
ok("Two packing lines", (xml.match(/<PackingLine>/g) || []).length === 2);
ok("KGS normalised to KG", /<Weight>231<\/Weight>\s*<WeightUnit>\s*<Code>KG<\/Code>/.test(xml));
const cfg = cwPublicConfig();
ok("auth is static-bearer", cfg.authMode === "static-bearer");
ok("booking URL is the training endpoint", cfg.bookingUrl === "https://cw-apim-se.azure-api.net/Copilot_CW_Test");
const result = await sendBookingToCw(xml, booking);
ok("CW responded ok (mock)", result.ok && result.status === 200);
ok("response carries a CW booking number", !!result.cwBookingNumber);
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
