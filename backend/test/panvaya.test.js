import assert from "node:assert/strict";
import { config } from "../src/lib/config.js";
import { getPortCongestion, cacheStats } from "../src/lib/portCongestionCache.js";
import { getTracking } from "../src/lib/trackingCache.js";
import { trackingRequestFor, trackingMapData, withLiveTracking, shipmentLifecycle, trackingEventDateTime } from "../../frontend/src/trackingData.js";

config.freightPulse.apiKey = "test-key";
config.freightPulse.mode = "live";
Object.assign(config.freightPulse, { baseUrl: "https://api.panvaya.com/api/v1", portPath: "/port-congestion", authHeader: "X-API-Key", authScheme: "", rateLimitPerMin: 5, monthlyQuota: 100, cacheTtlMs: 86400000 });
const originalFetch = globalThis.fetch;
let calls = [];
globalThis.fetch = async (url, options) => {
  calls.push({ url, options });
  assert.equal(options.headers["X-API-Key"], "test-key");
  if (url.endsWith("/track/ocean")) return new Response(JSON.stringify({ data: { reference: { number: "MSKU8094830" }, containers: [], status: "in_transit" }, errors: null }));
  if (url.endsWith("/track/air")) {
    if (JSON.parse(options.body).awb === "999-99999999") return new Response(JSON.stringify({ errors: [{ code: "NOT_FOUND", detail: "No tracking data" }] }), { status: 404 });
    return new Response(JSON.stringify({ awbNumber: "044-45428036", status: "IN_TRANSIT", events: [], arrivalEstimated: "2026-10-20T10:00:00" }));
  }
  return new Response(JSON.stringify({ count: 1, ports: [{ locode: "SGSIN", name: "Singapore", country: "SG", anchorLast30: { median: 0 }, capLast30: { vesselsArriving: 0 } }] }), { status: 200 });
};
try {
  const results = await Promise.all([getPortCongestion([" sgsin ", "SGSIN"]), getPortCongestion(["SGSIN"])]);
  assert.equal(calls.length, 1);
  assert.equal(calls[0].url, "https://api.panvaya.com/api/v1/port-congestion?locode=SGSIN");
  assert.equal(results[0].SGSIN.source, "live");
  assert.equal(results[0].SGSIN.congestionLevel, "Low");
  assert.equal(results[0].SGSIN.anchorWaitDays, 0);
  assert.equal(results[0].SGSIN.recentAvgPortCallsPerDay, 0);
  assert.equal(results[0].SGSIN.ratioVsBaseline, null);
  assert.equal((await getPortCongestion(["SGSIN"])).SGSIN.cached, true);
  assert.equal(calls.length, 1);
  assert.equal(cacheStats().callsThisMonth, 1);
  await Promise.all([getTracking({ mode: "SEA", container: " msku8094830 " }), getTracking({ mode: "Ocean", container: "MSKU8094830" })]);
  assert.equal(calls.length, 2);
  assert.deepEqual(JSON.parse(calls[1].options.body), { container: "MSKU8094830", include_route_data: true });
  assert.equal((await getTracking({ mode: "SEA", container: "MSKU8094830" })).cached, true);
  const air = await Promise.all([getTracking({ mode: "AIR", awb: "044-45428036" }), getTracking({ mode: "Air", awb: "04445428036" })]);
  assert.equal(calls.length, 3);
  assert.equal(air[0].data.arrivalEstimated, "2026-10-20T10:00:00");
  assert.deepEqual(JSON.parse(calls[2].options.body), { awb: "044-45428036" });
  await assert.rejects(getTracking({ mode: "AIR", awb: "invalid" }), { status: 400 });
  await assert.rejects(getTracking({ mode: "SEA", bol: "BL1", bk: "BK1" }), { status: 400 });
  assert.equal(calls.length, 3);
  await assert.rejects(getTracking({ mode: "AIR", awb: "99999999999" }), { status: 404, code: "NOT_FOUND" });
  await assert.rejects(getTracking({ mode: "AIR", awb: "999-99999999" }), { status: 404 });
  assert.equal(calls.length, 4);
  await getTracking({ mode: "SEA", bol: "BL123" });
  assert.deepEqual(JSON.parse(calls[4].options.body), { bol: "BL123", include_route_data: true });
  await assert.rejects(getTracking({ mode: "SEA", bk: "BK123" }), { status: 429 });
  assert.equal(calls.length, 5);
  assert.equal(cacheStats().callsThisMonth, 5);
  assert.equal((await getTracking({ mode: "AIR", awb: "04445428036" })).cached, true);
  const shipment = { id: "AIR1", raw: { Trans: "AIR", Master: "044-45428036" }, containers: [], events: [] };
  assert.deepEqual(trackingRequestFor(shipment), { mode: "AIR", awb: "04445428036" });
  assert.equal(trackingRequestFor({ raw: { Trans: "AIR", Master: "HOUSE123" } }), null);
  assert.deepEqual(trackingRequestFor({ raw: { Trans: "SEA", Master: "BL123" } }), { mode: "SEA", bol: "BL123" });
  const enriched = withLiveTracking(shipment, { mode: "air", data: { ...air[0].data, events: [{ code: "DEP", airportCode: "JFK", eventTime: "2026-10-15T10:00:00", actual: true }, { code: "DLV", airportCode: "LHR", eventTime: "2026-10-20T10:00:00", actual: false }] } });
  assert.equal(enriched.status, "IN_TRANSIT");
  assert.equal(enriched.eta, "2026-10-20T10:00:00");
  assert.equal(enriched.etaDate, "2026-10-20");
  assert.equal(enriched.etaTime, "10:00 (airport local)");
  assert.equal(trackingEventDateTime(enriched.events[0]), "2026-10-15 10:00:00 (JFK local)");
  assert.equal(shipmentLifecycle(enriched).activeIndex, 1);
  assert.equal(shipmentLifecycle(enriched).stages[4].reached, false);
  const ocean = withLiveTracking({ ...shipment, raw: { Trans: "SEA" } }, { mode: "ocean", data: { status: "in_transit", locations: [{ id: 1, locode: "SGSIN" }], transports: [{ id: 2, name: "VESSEL", mode: "vessel", voyage_number: "V1" }], containers: [{ number: "MSKU8094830", events: [{ id: 3, event_code: "DEPA", event_name: "Departure", location_id: 1, transport_id: 2, event_time: "2026-10-15T10:00:00Z", actual: true }] }] } });
  assert.equal(ocean.events[0].location, "SGSIN");
  assert.equal(ocean.events[0].description, "Departure / MSKU8094830 / VESSEL / V1");
  assert.equal(ocean.eta, "Not Available Now");
  assert.equal(shipmentLifecycle(ocean).activeIndex, 1);
  const transfer = withLiveTracking(shipment, { mode: "air", data: { ...air[0].data, destinationAirportCode: "LHR", events: [{ code: "ARR", airportCode: "DOH", eventTime: "2026-10-15T10:00:00", actual: true }] } });
  assert.equal(shipmentLifecycle(transfer).activeIndex, 2);
  assert.equal(shipmentLifecycle(transfer).stages[3].reached, false);
  const mapResult = trackingMapData({ mode: "ocean", cached: true, cachedAt: "2026-10-15T10:30:00Z", data: { route_data: { current_position: { latitude: 0, longitude: 0, estimated: false, source: "ais", observed_at: "2026-10-15T10:00:00Z" }, segments: [{ path: [[103.8, 1.2], [104, 2]] }] } } });
  assert.deepEqual(mapResult.position.point, { lat: 0, lng: 0 });
  assert.equal(mapResult.position.kind, "reported");
  assert.equal(mapResult.position.observedAt, "2026-10-15T10:00:00Z");
  assert.equal(mapResult.position.cached, true);
  assert.deepEqual(mapResult.paths[0][0], { lat: 1.2, lng: 103.8 });
  assert.equal(trackingMapData({ mode: "ocean", data: { route_data: { current_position: { latitude: 1, longitude: 2, estimated: true } } } }).position.kind, "estimated");
  assert.equal(trackingMapData({ mode: "ocean", data: { route_data: { current_position: { latitude: null, longitude: null } } } }).position, null);
  assert.equal(trackingMapData({ mode: "ocean", data: { route_data: { current_position: { latitude: 91, longitude: 0 } } } }).position, null);
  const airMap = trackingMapData({ mode: "air", data: { events: [{ orderId: 1, actual: true, lat: 40, lng: -73, airportCode: "JFK", eventTime: "2026-10-15T10:00:00" }, { orderId: 2, actual: false, lat: 51, lng: 0, airportCode: "LHR", eventTime: "2026-10-16T10:00:00" }] } });
  assert.equal(airMap.position.kind, "airport");
  assert.equal(airMap.position.place, "JFK");
  assert.equal(airMap.position.localTime, true);
  assert.equal(trackingMapData({ mode: "air", data: { events: [{ orderId: 1, actual: true, lat: 40, lng: -73 }, { orderId: 2, actual: true, lat: null, lng: null }] } }).position, null);
  assert.equal(trackingMapData({ mode: "air", data: { routePoints: [{ lat: 1, lng: 2 }], events: [] } }).position, null);
  console.log("Panvaya contracts, concurrent/repeated caches, canonical references, errors and shared rate limit tests passed");
} finally {
  globalThis.fetch = originalFetch;
}